#Conditional 
'''
Equal:  ==
Not Equal:  !=
Greater Than:   >
Less Than:  <
Greater or Equal:   >=
Less or Equal:  <=
Object Identity:    is
'''
num1=3
num2=5
print(num1==num2)
print(num1!=num2)
print(num1>num2)
print(num1<num2)
print(num1>=num2)
print(num1<=num2) 
num3='100'
num4='150'
print(num3+num4)
num3=int(num3)
num4=float(num4)
print(num3+num4)
